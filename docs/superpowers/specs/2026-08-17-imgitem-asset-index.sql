-- ImgItem 목록 조회 인덱스 — 수동 적용
--
-- 어드민 이미지 관리(/resource/assets)의 목록 조회는 `WHERE type = 'asset'` 으로
-- 거른 뒤 정렬해서 커서 페이징을 합니다. ImgItem 에는 `type` 에도 정렬 컬럼에도
-- 인덱스가 없어 페이지를 넘길 때마다 전체 스캔이 발생합니다. ImgItem 은 프로필·
-- 다이어리·인테리어·간식 이미지가 모두 들어가는 테이블이라 사용자 활동에 비례해
-- 커지므로, 데이터가 쌓일수록 이 조회는 계속 느려집니다.
--
-- 이 화면이 스피너에서 멈춰 있던 문제와는 무관합니다. 그쪽 원인은 프론트 번들의
-- 청크 하나가 문법 오류로 파싱되지 않아 하이드레이션이 진행되지 않은 것이었고,
-- 39244c3 에서 수정했습니다. 이 인덱스는 순수한 조회 성능 개선입니다.
--
-- 적용: dev 에서 먼저 적용해 EXPLAIN 결과를 확인한 뒤 prod 에 적용하세요.
-- 인덱스 추가만 하므로 기존 제약이나 데이터를 건드리지 않고, 되돌리려면 DROP 하면
-- 됩니다. 다만 테이블이 크면 생성에 시간이 걸리므로 트래픽이 적은 시간대를 권합니다.

-- ============================================================
-- BEFORE — 현재 인덱스와 실행 계획 확인
-- type=asset 행 수, 그리고 목록 쿼리가 어떻게 도는지 봅니다.
-- ============================================================

SHOW INDEX FROM `ImgItem`;

SELECT `type`, COUNT(*) AS rows_by_type FROM `ImgItem` GROUP BY `type`;

EXPLAIN
SELECT * FROM `ImgItem`
 WHERE `type` = 'asset'
 ORDER BY `id` DESC
 LIMIT 20;
-- 이 시점에는 type 필터를 인덱스로 처리하지 못해 전체 스캔이 나옵니다.


-- ============================================================
-- 인덱스 생성
-- (type, id) 순서가 중요합니다. type 으로 좁힌 뒤 id 로 정렬·커서 이동까지
-- 같은 인덱스로 처리됩니다.
-- ============================================================

CREATE INDEX `ImgItem_type_id_idx` ON `ImgItem`(`type`, `id`);


-- ============================================================
-- AFTER — 같은 EXPLAIN 을 다시 실행
-- key 컬럼에 ImgItem_type_id_idx 가 잡히고 rows 가 크게 줄어야 합니다.
-- ============================================================

EXPLAIN
SELECT * FROM `ImgItem`
 WHERE `type` = 'asset'
 ORDER BY `id` DESC
 LIMIT 20;


